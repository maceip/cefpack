def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true", help="Run offline unit/packaging self-test")
    parser.add_argument("--emit-mock-aar", type=Path, default=None, help="Optional output path for self-test AAR")
    parser.add_argument("--base-aar", type=Path)
    parser.add_argument("--arm64-so", type=Path)
    parser.add_argument("--x64-so", type=Path, default=None)
    parser.add_argument("--single-abi", action="store_true")
    parser.add_argument("--pak", type=Path)
    parser.add_argument("--icudtl", type=Path)
    parser.add_argument("--native-libs-srcjar", type=Path, default=None)
    parser.add_argument("--jni-registration-srcjar", type=Path, default=None)
    parser.add_argument("--javac", default=shutil.which("javac") or "javac")
    parser.add_argument("--output", type=Path, default=Path("cefpack-android.aar"))
    parser.add_argument("--bundle-dir", type=Path, default=Path("cef-bundle"))
    parser.add_argument("--chromium-version", default="158.0.8127.89")
    parser.add_argument(
        "--chromium-commit", default="1de57fa19722fa6d6841d4f596c394d015580656"
    )
    args = parser.parse_args()

    if args.self_test:
        run_self_test(args.javac, args.emit_mock_aar)
        return 0

    for flag, val in (
        ("--base-aar", args.base_aar),
        ("--arm64-so", args.arm64_so),
        ("--pak", args.pak),
        ("--icudtl", args.icudtl),
    ):
        if val is None or not val.is_file():
            parser.error(f"{flag} must point to an existing file (got {val})")

    if not args.single_abi and (args.x64_so is None or not args.x64_so.is_file()):
        parser.error("--x64-so must point to an existing file unless --single-abi is set")

    assemble_aar(
        base_aar=args.base_aar,
        arm64_so=args.arm64_so,
        x64_so=None if args.single_abi else args.x64_so,
        pak_path=args.pak,
        icudtl_path=args.icudtl,
        native_libs_srcjar=args.native_libs_srcjar,
        jni_registration_srcjar=args.jni_registration_srcjar,
        javac_bin=args.javac,
        output_aar=args.output,
        bundle_dir=args.bundle_dir,
        chromium_version=args.chromium_version,
        chromium_commit=args.chromium_commit,
    )
    print(f"Assembled and verified {args.output} ({output_size_mb(args.output):.2f} MiB)")
    return 0


def output_size_mb(path: Path) -> float:
    return path.stat().st_size / (1024 * 1024)


if __name__ == "__main__":
    sys.exit(main())
