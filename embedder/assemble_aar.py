"""Assemble and verify the multi-ABI cefpack-android.aar + cef-bundle directory.

Takes Chromium's `dist_aar` output (`cefpack_base.aar`) together with the built
arm64-v8a and x86_64 `libcefpack_content.so` binaries, `cefpack_resources.pak`,
`icudtl.dat`, and `cefpack_native_libraries_srcjar.srcjar`, then:

  1. Scans every `.class` constant pool in `classes.jar` to discover all
     `org/chromium/**/R` and `androidx/**/R` classes and fields referenced by
     Chromium's Android Java layer.
  2. Generates non-final delegating `R.java` classes that forward resource IDs
     at class-init time from `dev.cefpack.android.R.<type>.<name>` (generated by
     AGP in the consuming app from `R.txt`), with safe zero fallbacks for any
     unmerged optional resource fields so `NoSuchFieldError` cannot occur.
  3. Patches `org.chromium.build.NativeLibraries` from `--native-libs-srcjar` so
     `sCpuFamily` adapts at runtime between `CPU_FAMILY_ARM` and
     `CPU_FAMILY_X86` via `android.os.Build.SUPPORTED_ABIS`, `sSupport64Bit` is
     `true`, and `LIBRARIES` contains `{"cefpack_content"}`.
  4. Strips forbidden Play Services / Firebase / MLKit / Cefrium / WebOTP SMS
     classes and compile-only `dev/cefpack/android/R*.class` stubs from
     `classes.jar`.
  5. Packages `jni/arm64-v8a/libcefpack_content.so`,
     `jni/x86_64/libcefpack_content.so`, and uncompressed (`ZIP_STORED`)
     `assets/cefpack_resources.pak` + `assets/icudtl.dat` into
     `cefpack-android.aar`.
  6. Runs a strict self-audit on `cefpack-android.aar` (16 KB ELF64 `PT_LOAD`
     alignment, exported `JNI_OnLoad`, uncompressed `.pak`/`icudtl.dat`,
     required JNI/Chromium classes, zero forbidden prefixes, and isolated
     sandboxed/privileged service declarations with zero MTE/app_zygote flags)
     and populates `cef-bundle/` with `manifest.json` + `cefpack-android.aar`.
"""

