def verify_elf64_shared_lib(so_path: Path, expected_e_machine: int) -> set[str]:
    data = so_path.read_bytes()
    if len(data) < 64 or data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
        raise RuntimeError(f"{so_path} is not a little-endian ELF64 binary")
    e_type, e_machine = struct.unpack_from("<HH", data, 16)
    if e_type != 3:  # ET_DYN
        raise RuntimeError(f"{so_path} is not ET_DYN (e_type={e_type})")
    if e_machine != expected_e_machine:
        raise RuntimeError(
            f"{so_path} e_machine={e_machine}, expected {expected_e_machine}"
        )

    (e_phoff,) = struct.unpack_from("<Q", data, 32)
    (e_shoff,) = struct.unpack_from("<Q", data, 40)
    e_phentsize, e_phnum, e_shentsize, e_shnum, _ = struct.unpack_from("<HHHHH", data, 54)

    pt_load_count = 0
    for i in range(e_phnum):
        off = e_phoff + i * e_phentsize
        p_type, _flags, p_offset, p_vaddr, _paddr, _filesz, _memsz, p_align = struct.unpack_from(
            "<IIQQQQQQ", data, off
        )
        if p_type == 1:  # PT_LOAD
            pt_load_count += 1
            if p_align < 0x4000 or (p_align & (p_align - 1)) != 0:
                raise RuntimeError(
                    f"{so_path} PT_LOAD[{i}] p_align={hex(p_align)} < 0x4000 (16 KB required)"
                )
            if (p_vaddr - p_offset) % p_align != 0:
                raise RuntimeError(
                    f"{so_path} PT_LOAD[{i}] (p_vaddr - p_offset) not congruent mod {hex(p_align)}"
                )
    if pt_load_count == 0:
        raise RuntimeError(f"{so_path} has zero PT_LOAD segments")

    # Verify JNI_OnLoad is exported in .dynsym (SHT_DYNSYM = 11) and collect Java_* JNI exports.
    found_jni_onload = False
    jni_exports: set[str] = set()
    if e_shoff and e_shnum and e_shentsize >= 64:
        sections = []
        for i in range(e_shnum):
            soff = e_shoff + i * e_shentsize
            sh_name, sh_type, _sh_flags, _sh_addr, sh_offset, sh_size, sh_link, _info, _align, sh_entsize = (
                struct.unpack_from("<IIQQQQIIQQ", data, soff)
            )
            sections.append((sh_type, sh_offset, sh_size, sh_link, sh_entsize))
        for sh_type, sh_offset, sh_size, sh_link, sh_entsize in sections:
            if sh_type == 11 and sh_entsize >= 24 and 0 <= sh_link < len(sections):
                str_off = sections[sh_link][1]
                str_size = sections[sh_link][2]
                dynstr = data[str_off : str_off + str_size]
                for sym_off in range(sh_offset, sh_offset + sh_size, sh_entsize):
                    st_name, st_info, _other, st_shndx, _val, _sz = struct.unpack_from(
                        "<IBBHQQ", data, sym_off
                    )
                    if st_shndx == 0 or (st_info >> 4) == 0:
                        continue
                    end = dynstr.find(b"\x00", st_name)
                    if end == -1:
                        continue
                    sym_bytes = dynstr[st_name:end]
                    if sym_bytes == b"JNI_OnLoad":
                        found_jni_onload = True
                    elif sym_bytes.startswith(b"Java_"):
                        jni_exports.add(sym_bytes.decode("utf-8", errors="replace"))
    if not found_jni_onload:
        raise RuntimeError(f"{so_path} does not export defined global symbol JNI_OnLoad in .dynsym")
    return jni_exports


def verify_aar(aar_path: Path, require_x64: bool = True) -> None:
    with zipfile.ZipFile(aar_path, "r") as zf:
        infos = {i.filename: i for i in zf.infolist()}

        required_entries = [
            "AndroidManifest.xml",
            "classes.jar",
            "R.txt",
            "jni/arm64-v8a/libcefpack_content.so",
            "assets/cefpack_resources.pak",
            "assets/icudtl.dat",
        ]
        if require_x64:
            required_entries.append("jni/x86_64/libcefpack_content.so")

        for req in required_entries:
            if req not in infos or infos[req].file_size == 0:
                raise RuntimeError(f"AAR missing or empty required entry: {req}")

        for asset_name in ("assets/cefpack_resources.pak", "assets/icudtl.dat"):
            if infos[asset_name].compress_type != zipfile.ZIP_STORED:
                raise RuntimeError(
                    f"{asset_name} in {aar_path} must be ZIP_STORED (uncompressed), "
                    f"got compress_type={infos[asset_name].compress_type}"
                )

        manifest_xml = zf.read("AndroidManifest.xml").decode("utf-8")
        if "SandboxedProcessService0" not in manifest_xml or "SandboxedProcessService39" not in manifest_xml:
            raise RuntimeError("AAR AndroidManifest.xml missing SandboxedProcessService0..39")
        if "PrivilegedProcessService0" not in manifest_xml:
            raise RuntimeError("AAR AndroidManifest.xml missing PrivilegedProcessService0")
        for forbidden_attr in ("useAppZygote", "memtagMode"):
            if forbidden_attr in manifest_xml:
                raise RuntimeError(
                    f"AAR AndroidManifest.xml contains forbidden attribute '{forbidden_attr}'"
                )

        with tempfile.TemporaryDirectory() as tmp:
            tmp_path = Path(tmp)
            arm64_so = tmp_path / "arm64.so"
            arm64_so.write_bytes(zf.read("jni/arm64-v8a/libcefpack_content.so"))
            arm64_jni_syms = verify_elf64_shared_lib(arm64_so, expected_e_machine=183)  # EM_AARCH64

            if require_x64:
                x64_so = tmp_path / "x64.so"
                x64_so.write_bytes(zf.read("jni/x86_64/libcefpack_content.so"))
                x64_jni_syms = verify_elf64_shared_lib(x64_so, expected_e_machine=62)  # EM_X86_64
                if arm64_jni_syms != x64_jni_syms:
                    only_arm = sorted(arm64_jni_syms - x64_jni_syms)[:10]
                    only_x64 = sorted(x64_jni_syms - arm64_jni_syms)[:10]
                    raise RuntimeError(
                        f"Cross-ABI JNI symbol mismatch between arm64-v8a ({len(arm64_jni_syms)}) "
                        f"and x86_64 ({len(x64_jni_syms)}): arm64_only={only_arm}, x64_only={only_x64}"
                    )

            classes_jar = tmp_path / "classes.jar"
            classes_jar.write_bytes(zf.read("classes.jar"))
            with zipfile.ZipFile(classes_jar, "r") as cj:
                class_entries = set(cj.namelist())
                for c_entry in class_entries:
                    if not c_entry.endswith(".class"):
                        continue
                    c_bytes = cj.read(c_entry)
                    for bad_ref in (
                        b"com/google/android/gms/",
                        b"com/google/firebase/",
                        b"com/google/mlkit/",
                        b"com/cefrium/",
                    ):
                        if bad_ref in c_bytes:
                            raise RuntimeError(
                                f"classes.jar entry {c_entry} references forbidden symbol {bad_ref.decode()} in constant pool"
                            )

        for info_name in infos:
            if info_name.startswith("res/"):
                if re.match(r"^res/\d+_res/", info_name) or len(info_name.split("/")) != 3:
                    raise RuntimeError(f"AAR contains unflattened resource path: {info_name}")
                fname = info_name.split("/")[-1]
                if fname.startswith(("common_google_", "googleg_", "gshield_", "abc_")):
                    raise RuntimeError(f"AAR contains forbidden GMS/AppCompat resource: {info_name}")
                if info_name.endswith(".xml"):
                    rtxt_xml = zf.read(info_name).decode("utf-8", errors="replace")
                    if "gmscore" in rtxt_xml or "common_google_play_services" in rtxt_xml:
                        raise RuntimeError(f"AAR resource {info_name} contains GMS strings")

        r_txt_check = zf.read("R.txt").decode("utf-8", errors="replace")
        if "common_google_" in r_txt_check or "google_play_services_version" in r_txt_check:
            raise RuntimeError("AAR R.txt contains forbidden GMS Play Services symbols")
        seen_r_keys: set[tuple[str, str]] = set()
        for r_line in r_txt_check.splitlines():
            r_parts = r_line.strip().split(None, 3)
            if len(r_parts) >= 4:
                rk = (r_parts[1], r_parts[2])
                if rk in seen_r_keys:
                    raise RuntimeError(f"AAR R.txt contains duplicate symbol {rk}")
                seen_r_keys.add(rk)

        if "proguard.txt" in infos:
            pg_txt = zf.read("proguard.txt").decode("utf-8", errors="replace")
            if "-maximumremovedandroidloglevel" in pg_txt or "cr_allowunused" in pg_txt:
                raise RuntimeError("AAR proguard.txt contains internal Chromium R8 directives")

    required_classes = [
        "dev/cefpack/android/CefpackEngine.class",
        "dev/cefpack/android/CefpackSession.class",
        "dev/cefpack/android/CefpackViewAndroidDelegate.class",
        "org/jni_zero/GEN_JNI.class",
        "org/chromium/build/BuildConfig.class",
        "org/chromium/build/NativeLibraries.class",
        "androidx/interpolator/view/animation/FastOutExtraSlowInInterpolator.class",
    ]
    for cls in required_classes:
        if cls not in class_entries:
            raise RuntimeError(f"classes.jar missing required class: {cls}")

    for entry in class_entries:
        if entry == "dev/cefpack/android/R.class" or entry.startswith("dev/cefpack/android/R$"):
            raise RuntimeError(f"classes.jar must not package app-level R stub: {entry}")
        if entry == "androidx/interpolator/view/animation/FastOutExtraSlowInInterpolator.class":
            continue
        for prefix in FORBIDDEN_CLASS_PREFIXES + STRIPPED_EXTERNAL_CLASS_PREFIXES:
            if entry.startswith(prefix):
                raise RuntimeError(f"classes.jar contains forbidden/duplicate external class: {entry}")
        if entry == "com/google/common/util/concurrent/ListenableFuture.class":
            raise RuntimeError("classes.jar contains duplicate ListenableFuture.class")


def assemble_aar(
    base_aar: Path,
    arm64_so: Path,
    x64_so: Path | None,
    pak_path: Path,
    icudtl_path: Path,
    native_libs_srcjar: Path | None,
    javac_bin: str,
    output_aar: Path,
    bundle_dir: Path | None,
    chromium_version: str,
    chromium_commit: str,
    jni_registration_srcjar: Path | None = None,
) -> None:
    verify_elf64_shared_lib(arm64_so, expected_e_machine=183)
    if x64_so is not None:
        verify_elf64_shared_lib(x64_so, expected_e_machine=62)

    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        unpacked = work / "base_aar"
        unpacked.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(base_aar, "r") as zf:
            zf.extractall(unpacked)

        raw_r_txt_path = unpacked / "R.txt"
        if not raw_r_txt_path.is_file():
            raw_r_txt_path.write_text("", encoding="utf-8")
        kept_res, pruned_r_txt_bytes = collect_chromium_resources_and_r_txt(
            unpacked / "res", raw_r_txt_path
        )
        r_txt_path = work / "pruned_R.txt"
        r_txt_path.write_bytes(pruned_r_txt_bytes)
        r_txt_resources = parse_r_txt(r_txt_path)

        orig_classes_jar = unpacked / "classes.jar"
        all_r_classes: set[tuple[str, str | None]] = set()
        all_r_fields: dict[tuple[str, str], dict[str, str]] = defaultdict(dict)

        with zipfile.ZipFile(orig_classes_jar, "r") as cj:
            for info in cj.infolist():
                if not info.filename.endswith(".class") or is_excluded_jar_entry(info.filename):
                    continue
                cls_refs, fld_refs = scan_class_constant_pool(cj.read(info.filename))
                all_r_classes |= cls_refs
                for key, fmap in fld_refs.items():
                    all_r_fields[key].update(fmap)

        gen_src_dir = work / "gen_src"
        gen_cls_dir = work / "gen_cls"
        gen_src_dir.mkdir(parents=True, exist_ok=True)
        gen_cls_dir.mkdir(parents=True, exist_ok=True)

        java_files = write_stub_and_delegating_r_sources(
            gen_src_dir, r_txt_resources, all_r_classes, all_r_fields
        )
        java_files.append(
            prepare_multi_abi_native_libraries_java(gen_src_dir, native_libs_srcjar)
        )
        java_files.extend(write_fast_out_extra_slow_in_interpolator(gen_src_dir))
        has_jni_reg_srcjar = False
        if jni_registration_srcjar is not None and jni_registration_srcjar.is_file():
            with zipfile.ZipFile(jni_registration_srcjar, "r") as sj:
                for entry_name in sorted(sj.namelist()):
                    if entry_name.endswith(".java"):
                        dst_java = gen_src_dir / entry_name
                        dst_java.parent.mkdir(parents=True, exist_ok=True)
                        dst_java.write_bytes(sj.read(entry_name))
                        java_files.append(dst_java)
                        has_jni_reg_srcjar = True

        argfile = work / "javac_sources.txt"
        argfile.write_text("\n".join(str(p) for p in java_files) + "\n", encoding="utf-8")
        subprocess.run(
            [
                javac_bin,
                "--release",
                "17",
                "-g:none",
                "-d",
                str(gen_cls_dir),
                f"@{argfile}",
            ],
            check=True,
        )

        rebuilt_jar = work / "rebuilt_classes.jar"
        seen_jar_entries: set[str] = set()
        with zipfile.ZipFile(rebuilt_jar, "w", compression=zipfile.ZIP_DEFLATED) as out_jar:
            with zipfile.ZipFile(orig_classes_jar, "r") as in_jar:
                for info in sorted(in_jar.infolist(), key=lambda i: i.filename):
                    if info.is_dir() or is_excluded_jar_entry(info.filename):
                        continue
                    if has_jni_reg_srcjar and (
                        info.filename == "org/jni_zero/GEN_JNI.class"
                        or info.filename.startswith("org/jni_zero/GEN_JNI$")
                    ):
                        continue
                    if info.filename in seen_jar_entries:
                        continue
                    seen_jar_entries.add(info.filename)
                    zi = zipfile.ZipInfo(info.filename, date_time=(2026, 1, 1, 0, 0, 0))
                    zi.compress_type = zipfile.ZIP_DEFLATED
                    out_jar.writestr(zi, in_jar.read(info.filename))

            for compiled in sorted(gen_cls_dir.rglob("*.class")):
                rel = compiled.relative_to(gen_cls_dir).as_posix()
                if (
                    rel.startswith("android/")
                    or rel == "dev/cefpack/android/R.class"
                    or rel.startswith("dev/cefpack/android/R$")
                ):
                    continue
                if rel in seen_jar_entries:
                    continue
                seen_jar_entries.add(rel)
                zi = zipfile.ZipInfo(rel, date_time=(2026, 1, 1, 0, 0, 0))
                zi.compress_type = zipfile.ZIP_DEFLATED
                out_jar.writestr(zi, compiled.read_bytes())

        output_aar.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(output_aar, "w") as out_aar:
            def write_aar_entry(arcname: str, payload: bytes, stored: bool = False) -> None:
                zi = zipfile.ZipInfo(arcname, date_time=(2026, 1, 1, 0, 0, 0))
                zi.compress_type = zipfile.ZIP_STORED if stored else zipfile.ZIP_DEFLATED
                out_aar.writestr(zi, payload)

            write_aar_entry(
                "AndroidManifest.xml", (unpacked / "AndroidManifest.xml").read_bytes()
            )
            write_aar_entry("classes.jar", rebuilt_jar.read_bytes())
            write_aar_entry("R.txt", r_txt_path.read_bytes())
            write_aar_entry("proguard.txt", CONSUMER_PROGUARD_RULES.encode("utf-8"))

            for rel_res, res_payload in sorted(kept_res.items()):
                write_aar_entry(rel_res, res_payload)

            write_aar_entry("jni/arm64-v8a/libcefpack_content.so", arm64_so.read_bytes())
            if x64_so is not None:
                write_aar_entry("jni/x86_64/libcefpack_content.so", x64_so.read_bytes())

            # Critical: .pak and icudtl.dat MUST be ZIP_STORED so Chromium can mmap APK fds directly.
            write_aar_entry("assets/cefpack_resources.pak", pak_path.read_bytes(), stored=True)
            write_aar_entry("assets/icudtl.dat", icudtl_path.read_bytes(), stored=True)

    verify_aar(output_aar, require_x64=(x64_so is not None))

    if bundle_dir is not None:
        if bundle_dir.exists():
            shutil.rmtree(bundle_dir)
        (bundle_dir / "lib/arm64-v8a").mkdir(parents=True, exist_ok=True)
        (bundle_dir / "assets").mkdir(parents=True, exist_ok=True)
        shutil.copy2(output_aar, bundle_dir / "cefpack-android.aar")
        shutil.copy2(arm64_so, bundle_dir / "lib/arm64-v8a/libcefpack_content.so")
        abis = ["arm64-v8a"]
        if x64_so is not None:
            (bundle_dir / "lib/x86_64").mkdir(parents=True, exist_ok=True)
            shutil.copy2(x64_so, bundle_dir / "lib/x86_64/libcefpack_content.so")
            abis.append("x86_64")
        shutil.copy2(pak_path, bundle_dir / "assets/cefpack_resources.pak")
        shutil.copy2(icudtl_path, bundle_dir / "assets/icudtl.dat")

        manifest_data = {
            "schema": 2,
            "artifact": "cefpack-android.aar",
            "aar_sha256": sha256_file(output_aar),
            "chromium_version": chromium_version,
            "chromium_commit": chromium_commit,
            "abis": abis,
            "min_sdk": 29,
            "native_library": "libcefpack_content.so",
            "assets": ["cefpack_resources.pak", "icudtl.dat"],
        }
        (bundle_dir / "manifest.json").write_text(
            json.dumps(manifest_data, indent=2) + "\n", encoding="utf-8"
        )


def _make_synthetic_elf64_so(path: Path, e_machine: int) -> None:
    """Build a minimal valid 16KB-aligned ELF64 ET_DYN exporting global JNI_OnLoad."""
    dynstr = b"\x00JNI_OnLoad\x00"
    # Elf64_Sym: st_name(I), st_info(B), st_other(B), st_shndx(H), st_value(Q), st_size(Q)
    sym_null = struct.pack("<IBBHQQ", 0, 0, 0, 0, 0, 0)
    # STB_GLOBAL (1<<4) | STT_FUNC (2) = 0x12, defined in section 1
    sym_onload = struct.pack("<IBBHQQ", 1, 0x12, 0, 1, 0x1000, 16)
    dynsym = sym_null + sym_onload

    shstrtab = b"\x00.text\x00.dynsym\x00.dynstr\x00.shstrtab\x00"
    e_phoff = 64
    phentsize = 56
    phnum = 1

    text_off = 0x4000
    text_bytes = b"\xc0\x03\x5f\xd6" * 4

    dynsym_off = text_off + len(text_bytes)
    dynstr_off = dynsym_off + len(dynsym)
    shstr_off = dynstr_off + len(dynstr)
    shoff = (shstr_off + len(shstrtab) + 7) & ~7

    ehdr = struct.pack(
        "<16sHHIQQQIHHHHHH",
        b"\x7fELF\x02\x01\x01" + b"\x00" * 9,
        3,  # ET_DYN
        e_machine,
        1,
        0,
        e_phoff,
        shoff,
        0,
        64,
        phentsize,
        phnum,
        64,
        5,  # 5 sections: null, .text, .dynsym, .dynstr, .shstrtab
        4,
    )
    phdr = struct.pack(
        "<IIQQQQQQ",
        1,  # PT_LOAD
        5,  # PF_R | PF_X
        0,
        0,
        0,
        shoff,
        shoff,
        0x4000,  # 16 KB alignment
    )

    def shdr(name_off: int, sh_type: int, flags: int, offset: int, size: int, link: int = 0, entsize: int = 0) -> bytes:
        return struct.pack(
            "<IIQQQQIIQQ",
            name_off,
            sh_type,
            flags,
            0,
            offset,
            size,
            link,
            0,
            8,
            entsize,
        )

    shdrs = b"".join(
        [
            shdr(0, 0, 0, 0, 0),
            shdr(1, 1, 6, text_off, len(text_bytes)),       # .text (SHT_PROGBITS)
            shdr(7, 11, 2, dynsym_off, len(dynsym), link=3, entsize=24),  # .dynsym -> .dynstr (idx 3)
            shdr(15, 3, 2, dynstr_off, len(dynstr)),        # .dynstr (SHT_STRTAB)
            shdr(23, 3, 0, shstr_off, len(shstrtab)),       # .shstrtab
        ]
    )

    buf = bytearray(shoff + len(shdrs))
    buf[0 : len(ehdr)] = ehdr
    buf[e_phoff : e_phoff + len(phdr)] = phdr
    buf[text_off : text_off + len(text_bytes)] = text_bytes
    buf[dynsym_off : dynsym_off + len(dynsym)] = dynsym
    buf[dynstr_off : dynstr_off + len(dynstr)] = dynstr
    buf[shstr_off : shstr_off + len(shstrtab)] = shstrtab
    buf[shoff : shoff + len(shdrs)] = shdrs
    path.write_bytes(bytes(buf))


def run_self_test(javac_bin: str, emit_mock_aar: Path | None = None) -> None:
    repo_root = Path(__file__).resolve().parent.parent
