R_CLASS_RE = re.compile(r"^(?:([A-Za-z0-9_$]+(?:/[A-Za-z0-9_$]+)*)/)?R(?:\$([A-Za-z0-9_]+))?$")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fp:
        for chunk in iter(lambda: fp.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def parse_r_txt(r_txt_path: Path) -> dict[str, dict[str, str]]:
    """Return {res_type: {field_name: java_type ('int' | 'int[]')}} from R.txt."""
    resources: dict[str, dict[str, str]] = defaultdict(dict)
    if not r_txt_path.is_file():
        return resources
    for raw_line in r_txt_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line:
            continue
        parts = line.split(None, 3)
        if len(parts) < 4:
            continue
        java_type, res_type, name, _val = parts
        if java_type in ("int", "int[]"):
            resources[res_type][name] = java_type
    return resources


def scan_class_constant_pool(data: bytes) -> tuple[set[tuple[str, str | None]], dict[tuple[str, str], dict[str, str]]]:
    """Scan a JVM .class constant pool for R class and R$type field references.

    Returns:
      - r_classes: set of (pkg_slash, inner_type_or_None)
      - r_fields: {(pkg_slash, inner_type): {field_name: descriptor ('I' | '[I')}}
    """
    r_classes: set[tuple[str, str | None]] = set()
    r_fields: dict[tuple[str, str], dict[str, str]] = defaultdict(dict)

    if len(data) < 10:
        return r_classes, r_fields
    magic, _minor, _major, cp_count = struct.unpack_from(">IHHI", data, 0)
    if magic != 0xCAFEBABE or cp_count < 1:
        return r_classes, r_fields

    utf8_pool: dict[int, str] = {}
    class_pool: dict[int, int] = {}
    nat_pool: dict[int, tuple[int, int]] = {}
    field_refs: list[tuple[int, int]] = []

    offset = 10
    idx = 1
    while idx < cp_count and offset < len(data):
        tag = data[offset]
        offset += 1
        if tag == 1:  # CONSTANT_Utf8
            (length,) = struct.unpack_from(">H", data, offset)
            offset += 2
            utf8_pool[idx] = data[offset : offset + length].decode("utf-8", errors="replace")
            offset += length
        elif tag in (3, 4):  # Integer, Float
            offset += 4
        elif tag in (5, 6):  # Long, Double (occupy 2 constant-pool slots)
            offset += 8
            idx += 1
        elif tag == 7:  # CONSTANT_Class
            (name_idx,) = struct.unpack_from(">H", data, offset)
            offset += 2
            class_pool[idx] = name_idx
        elif tag in (8, 16, 19, 20):  # String, MethodType, Module, Package
            offset += 2
        elif tag == 9:  # CONSTANT_Fieldref
            cls_idx, nat_idx = struct.unpack_from(">HH", data, offset)
            offset += 4
            field_refs.append((cls_idx, nat_idx))
        elif tag in (10, 11, 17, 18):  # Methodref, InterfaceMethodref, Dynamic, InvokeDynamic
            offset += 4
        elif tag == 12:  # CONSTANT_NameAndType
            name_idx, desc_idx = struct.unpack_from(">HH", data, offset)
            offset += 4
            nat_pool[idx] = (name_idx, desc_idx)
        elif tag == 15:  # CONSTANT_MethodHandle
            offset += 3
        else:
            break
        idx += 1

    for _cls_slot, name_idx in class_pool.items():
        cls_name = utf8_pool.get(name_idx, "")
        m = R_CLASS_RE.match(cls_name)
        if not m:
            continue
        pkg = m.group(1) or ""
        inner = m.group(2)
        if pkg != "org/chromium" and not pkg.startswith("org/chromium/"):
            continue
        r_classes.add((pkg, inner))

    for cls_idx, nat_idx in field_refs:
        cls_name = utf8_pool.get(class_pool.get(cls_idx, -1), "")
        m = R_CLASS_RE.match(cls_name)
        if not m or not m.group(2):
            continue
        pkg = m.group(1) or ""
        inner = m.group(2)
        if pkg != "org/chromium" and not pkg.startswith("org/chromium/"):
            continue
        nat = nat_pool.get(nat_idx)
        if not nat:
            continue
        field_name = utf8_pool.get(nat[0], "")
        desc = utf8_pool.get(nat[1], "")
        if field_name and desc in ("I", "[I"):
            r_classes.add((pkg, inner))
            r_fields[(pkg, inner)][field_name] = desc

    return r_classes, r_fields


def is_excluded_jar_entry(entry_name: str) -> bool:
    if entry_name.startswith("META-INF/") or entry_name.endswith(".kotlin_module") or entry_name == "module-info.class":
        return True
    for prefix in FORBIDDEN_CLASS_PREFIXES:
        if entry_name.startswith(prefix):
            return True
    for prefix in STRIPPED_EXTERNAL_CLASS_PREFIXES:
        if entry_name.startswith(prefix):
            return True
    if entry_name == "com/google/common/util/concurrent/ListenableFuture.class":
        return True
    if entry_name in ("org/chromium/build/NativeLibraries.class",) or entry_name.startswith(
        "org/chromium/build/NativeLibraries$"
    ):
        return True
    if entry_name.endswith(".class"):
        internal = entry_name[:-6]
        m = R_CLASS_RE.match(internal)
        if m:
            pkg = m.group(1) or ""
            if pkg != "android" and not pkg.startswith("android/"):
                return True
    return False


def collect_chromium_resources_and_r_txt(
    res_dir: Path, raw_r_txt: Path
) -> tuple[dict[str, bytes], bytes]:
    """Flatten `res/<N>_res/<dir>/<file>` -> `res/<dir>/<file>`, strip fat-bundled
    GMS / AndroidX resources, and prune `R.txt` to match the kept resource set.
    """
    kept_res: dict[str, bytes] = {}
    defined_res: set[tuple[str, str]] = set()

    if res_dir.is_dir():
        for res_file in sorted(res_dir.rglob("*")):
            if not res_file.is_file():
                continue
            orig_rel = "res/" + res_file.relative_to(res_dir).as_posix()
            flat_rel = re.sub(r"^res/\d+_res/", "res/", orig_rel)
            parts = flat_rel.split("/")
            if len(parts) != 3:
                continue
            _, rdir, fname = parts
            payload = res_file.read_bytes()

            if rdir.startswith("values"):
                if not fname.endswith(".xml"):
                    continue
                txt = payload.decode("utf-8", errors="replace")
                if "gmscore" in txt or "common_google_play_services" in txt:
                    continue
                if not (
                    fname.startswith(("android_content_strings", "android_ui_strings", "strings_0."))
                    or "cefpack_engine_name" in txt
                    or "cefpack_webview_app_name" in txt
                    or "The Chromium Authors" in txt
                ):
                    continue
                kept_res[flat_rel] = payload
                root = ET.fromstring(txt)
                for elem in root:
                    tag = elem.tag
                    name = elem.attrib.get("name")
                    if not name:
                        continue
                    name_norm = name.replace(".", "_")
                    if tag == "item":
                        rtype = elem.attrib.get("type")
                        if rtype:
                            defined_res.add((rtype, name_norm))
                    elif tag == "declare-styleable":
                        defined_res.add(("styleable", name_norm))
                        for attr in elem:
                            aname = attr.attrib.get("name")
                            if aname:
                                defined_res.add(
                                    (
                                        "styleable",
                                        f"{name_norm}_{aname.replace(':', '_').replace('.', '_')}",
                                    )
                                )
                                if ":" not in aname:
                                    defined_res.add(("attr", aname.replace(".", "_")))
                    elif tag in (
                        "string",
                        "color",
                        "dimen",
                        "style",
                        "attr",
                        "id",
                        "integer",
                        "bool",
                        "array",
                        "string-array",
                        "integer-array",
                        "plurals",
                        "fraction",
                    ):
                        rtype = "array" if tag.endswith("-array") else tag
                        defined_res.add((rtype, name_norm))
            else:
                if fname.startswith(DROP_NONVAL_RESOURCE_PREFIXES):
                    continue
                kept_res[flat_rel] = payload
                rtype = rdir.split("-")[0]
                bname = fname.split(".")[0]
                defined_res.add((rtype, bname))
                if fname.endswith(".xml"):
                    txt = payload.decode("utf-8", errors="replace")
                    for id_m in re.findall(r"@\+id/([A-Za-z0-9_.]+)", txt):
                        defined_res.add(("id", id_m.replace(".", "_")))

    dedup_r: dict[tuple[str, str], str] = {}
    dedup_order: list[tuple[str, str]] = []
    if raw_r_txt.is_file():
        for line in raw_r_txt.read_text(encoding="utf-8").splitlines():
            parts = line.strip().split(None, 3)
            if len(parts) < 4:
                continue
            _jtype, rtype, rname, rval = parts
            if rname.startswith("common_google_") or rname == "google_play_services_version":
                continue
            if (rtype, rname) not in defined_res:
                continue
            key = (rtype, rname)
            if key not in dedup_r:
                dedup_order.append(key)
                dedup_r[key] = line.strip()
            else:
                prev_val = dedup_r[key].split(None, 3)[3]
                if prev_val in ("0", "0x0", "0x00000000") and rval not in ("0", "0x0", "0x00000000"):
                    dedup_r[key] = line.strip()

    pruned_lines = [dedup_r[k] for k in dedup_order]
    pruned_bytes = ("\n".join(pruned_lines) + ("\n" if pruned_lines else "")).encode("utf-8")
    return kept_res, pruned_bytes


def write_stub_and_delegating_r_sources(
    src_dir: Path,
    r_txt_resources: dict[str, dict[str, str]],
    r_classes: set[tuple[str, str | None]],
    r_fields: dict[tuple[str, str], dict[str, str]],
) -> list[Path]:
    java_files: list[Path] = []

    # 1. Compile-time-only stub for dev.cefpack.android.R (never packaged into classes.jar).
    stub_pkg_dir = src_dir / "dev/cefpack/android"
    stub_pkg_dir.mkdir(parents=True, exist_ok=True)
    stub_lines = [
        "package dev.cefpack.android;",
        "public final class R {",
    ]
    all_stub_types = sorted(set(r_txt_resources.keys()))
    for res_type in all_stub_types:
        stub_lines.append(f"    public static final class {res_type} {{")
        for field_name, java_type in sorted(r_txt_resources[res_type].items()):
            init = "0" if java_type == "int" else "new int[0]"
            stub_lines.append(f"        public static {java_type} {field_name} = {init};")
        stub_lines.append("    }")
    stub_lines.append("}")
    stub_file = stub_pkg_dir / "R.java"
    stub_file.write_text("\n".join(stub_lines) + "\n", encoding="utf-8")
    java_files.append(stub_file)

    # 2. Group referenced packages -> inner resource types.
    pkg_to_inners: dict[str, set[str]] = defaultdict(set)
    for pkg, inner in r_classes:
        pkg_to_inners[pkg]  # ensure package key exists even if bare R class was referenced
        if inner:
            pkg_to_inners[pkg].add(inner)
    for (pkg, inner) in r_fields:
        pkg_to_inners[pkg].add(inner)

    for pkg, inners in sorted(pkg_to_inners.items()):
        if not pkg:
            continue
        pkg_dir = src_dir / pkg
        pkg_dir.mkdir(parents=True, exist_ok=True)
        pkg_dots = pkg.replace("/", ".")
        lines = [
            f"package {pkg_dots};",
            "public final class R {",
        ]
        # Union of explicitly referenced inner types and R.txt types so reflection/lookups succeed.
        merged_inners = sorted(inners | set(r_txt_resources.keys()))
        for inner in merged_inners:
            lines.append(f"    public static final class {inner} {{")
            emitted: dict[str, tuple[str, str]] = {}
            for field_name, java_type in sorted(r_txt_resources.get(inner, {}).items()):
                emitted[field_name] = (
                    java_type,
                    f"dev.cefpack.android.R.{inner}.{field_name}",
                )
            for field_name, desc in sorted(r_fields.get((pkg, inner), {}).items()):
                java_type = "int" if desc == "I" else "int[]"
                if field_name not in emitted or emitted[field_name][0] != java_type:
                    fallback = "0" if java_type == "int" else "new int[0]"
                    emitted[field_name] = (java_type, fallback)
            for field_name, (java_type, expr) in sorted(emitted.items()):
                # Non-final static field so javac emits runtime GETSTATIC in <clinit>
                # instead of constant-folding 0 at compile time.
                lines.append(f"        public static {java_type} {field_name} = {expr};")
            lines.append("    }")
        lines.append("}")
        out_java = pkg_dir / "R.java"
        out_java.write_text("\n".join(lines) + "\n", encoding="utf-8")
        java_files.append(out_java)

    return java_files


def prepare_multi_abi_native_libraries_java(
    src_dir: Path, native_libs_srcjar: Path | None
) -> Path:
    out_dir = src_dir / "org/chromium/build"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_java = out_dir / "NativeLibraries.java"

    raw_src: str | None = None
    if native_libs_srcjar and native_libs_srcjar.is_file():
        with zipfile.ZipFile(native_libs_srcjar, "r") as zf:
            for name in zf.namelist():
                if name.endswith("NativeLibraries.java"):
                    raw_src = zf.read(name).decode("utf-8")
                    break

    cpu_expr = (
        'java.lang.System.getProperty("os.arch", "").contains("86") '
        "? CPU_FAMILY_X86 : CPU_FAMILY_ARM"
    )

    if raw_src:
        patched = re.sub(
            r"(public\s+static\s+)(?:final\s+)?(int\s+sCpuFamily\s*=\s*)[^;]+;",
            rf"\1\2{cpu_expr};",
            raw_src,
        )
        patched = re.sub(
            r"(public\s+static\s+(?:final\s+)?boolean\s+sSupport64Bit\s*=\s*)[^;]+;",
            r"\1true;",
            patched,
        )
        if '"cefpack_content"' not in patched:
            patched = re.sub(
                r"(LIBRARIES\s*=\s*)\{[^}]*\}",
                r'\1{"cefpack_content"}',
                patched,
            )
        out_java.write_text(patched, encoding="utf-8")
    else:
        out_java.write_text(
            f"""package org.chromium.build;

public class NativeLibraries {{
    public static final int CPU_FAMILY_UNKNOWN = 0;
    public static final int CPU_FAMILY_ARM = 1;
    public static final int CPU_FAMILY_MIPS = 2;
    public static final int CPU_FAMILY_X86 = 3;
    public static final int CPU_FAMILY_RISCV = 4;

    public static boolean sUseLinker;
    public static final String[] LIBRARIES = {{"cefpack_content"}};
    public static int sCpuFamily = {cpu_expr};
    public static boolean sSupport32Bit;
    public static boolean sSupport64Bit = true;
}}
""",
            encoding="utf-8",
        )
    return out_java


